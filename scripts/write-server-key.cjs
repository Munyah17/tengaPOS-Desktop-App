// The license server's Ed25519 public key is the trust anchor for update
// verification in electron/main.cjs — it must ship inside the packaged app,
// not come from the renderer. Vite only embeds VITE_* vars in the renderer
// bundle, so this script stamps the same value into a CommonJS module the
// main process can require(). Output is gitignored; re-run every build.
//
// Reads process.env first, then .env files in Vite's build-mode precedence
// order (lowest first so later files win), so a key set only in
// .env.production still reaches the main process.
const fs = require('node:fs')
const path = require('node:path')

const KEY = 'VITE_DESKTOP_LICENSE_PUBLIC_KEY'
const root = path.join(__dirname, '..')

const fromEnvFiles = {}
for (const name of ['.env', '.env.local', '.env.production', '.env.production.local']) {
  let text
  try {
    text = fs.readFileSync(path.join(root, name), 'utf8')
  } catch {
    continue
  }
  for (const line of text.split('\n')) {
    const m = line.match(/^\s*(?:export\s+)?([\w.-]+)\s*=\s*(.*)$/)
    if (!m) continue
    const val = m[2].trim().replace(/^(["'])(.*)\1\s*$/, '$2')
    fromEnvFiles[m[1]] = val
  }
}

const key = process.env[KEY] || fromEnvFiles[KEY] || ''
const out = path.join(root, 'electron', 'license-server-key.cjs')
fs.writeFileSync(
  out,
  '// GENERATED by scripts/write-server-key.cjs — do not edit or commit\n' +
    `module.exports = ${JSON.stringify(key)}\n`,
)
if (!key) {
  console.warn(`[write-server-key] ${KEY} is unset — this build will refuse to apply updates`)
}
